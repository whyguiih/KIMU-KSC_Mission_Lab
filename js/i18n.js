Object.keys(EXTRA_I18N).forEach((lang) => {
  if (window.I18N[lang]) {
    Object.assign(window.I18N[lang], EXTRA_I18N[lang]);
  }
});

window.currentLang = 'pt-BR';

window.t = function(key) {
  const dict = window.I18N[window.currentLang] || window.I18N['pt-BR'];
  return dict[key] || window.I18N['en-US'][key] || window.I18N['pt-BR'][key] || key;
};

window.pickI18n = function(obj) {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  if (obj[window.currentLang]) return obj[window.currentLang];
  return obj['en-US'] || obj['pt-BR'] || '';
};

window.setLanguage = function(lang) {
  if (window.I18N[lang]) {
    window.currentLang = lang;
    window.I18N.currentLang = lang;
    document.documentElement.lang = lang;
    if (typeof window.onLanguageChanged === 'function') {
      window.onLanguageChanged(lang);
    }
  }
};

window.I18N.currentLang = window.currentLang;
window.I18N.t = window.t;
window.I18N.pick = window.pickI18n;
window.I18N.setLanguage = window.setLanguage;
window.I18N.getLangMeta = function(code) {
  return window.LANGUAGES_LIST.find((l) => l.code === (code || window.currentLang)) || window.LANGUAGES_LIST[0];
};
